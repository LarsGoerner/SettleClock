const unsigned char * graphics_font32_get(char c)
{
        if (c >= 'A' && c <= 'Z') {
                return FONT_32PX_LETTERS[c - 'A'];
        } else if (c >= 'a' && c <= 'z') {
                return FONT_32PX_LETTERS[c - 'a'];
        } else if (c >= '0' && c <= '9') {
                return FONT_32PX_NUMBERS[c - '0'];
        } else if (c == ' ') {
                return FONT_32PX_SYMBOLS[0];
        } else if (c == '!') {
                return FONT_32PX_SYMBOLS[1];
        } else if (c == '?') {
                return FONT_32PX_SYMBOLS[2];
        } else if (c == '.') {
                return FONT_32PX_SYMBOLS[3];
        } else if (c == ',') {
                return FONT_32PX_SYMBOLS[4];
        } else if (c == 1) { // up
                return FONT_32PX_SYMBOLS[5];
        } else if (c == 2) { // down
                return FONT_32PX_SYMBOLS[6];
        } else if (c == 3) { // right
                return FONT_32PX_SYMBOLS[7];
        } else {
                return FONT_32P_INVAL_SYMBOL;
        }
}